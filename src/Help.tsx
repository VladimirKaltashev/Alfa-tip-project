export function Help({
  role = 'guest',
  embedded = false,
}: {
  role?: HelpRole;
  embedded?: boolean;
}) {
  const title =
    role === 'manager'
      ? 'Помощь заведению'
      : role === 'waiter'
        ? 'Помощь сотруднику'
        : 'Помощь гостю';
  const content = (
    <>
      {!embedded && (
        <a className="back" href={role === 'waiter' ? '/waiter' : '/'}>
          <ArrowLeft size={18} /> {role === 'waiter' ? 'В кабинет сотрудника' : 'К чаевым'}
        </a>
      )}
      <h1>{title}</h1>
      <p>Действия в сервисе «Альфа Чаевые» — от первого шага до результата.</p>
      <div className="help-grid">
        {entries[role].map((entry, index) => (
          <details key={entry.title} open={index === 0}>
            <summary>{entry.title}</summary>
            <p>{entry.text}</p>
            {entry.href && (
              <a className="text-button" href={entry.href}>
                {entry.link}
              </a>
            )}
          </details>
        ))}
        <details>
          <summary>Как сохраняются данные?</summary>
          <p>
            Данные хранятся на сервере и разделены по заведению и правам доступа. Сообщение об
            успехе появляется после подтверждения записи. Если данные изменились в другой вкладке
            или на другом устройстве, сохранение отклоняется: скопируйте введённый текст, обновите
            страницу и внесите изменения заново. При ошибке связи запрос мог успеть выполниться —
            сначала проверьте результат после обновления. Гостевая история привязана к этому
            браузеру: после удаления cookie она станет недоступна.
          </p>
        </details>
      </div>
    </>
  );
  return embedded ? (
    <section className="help-page bank-help">{content}</section>
  ) : (
    <main className="help-page">{content}</main>
  );
}
